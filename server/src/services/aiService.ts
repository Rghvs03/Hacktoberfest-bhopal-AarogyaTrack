import { config } from '../config';
import { GoogleGenerativeAI } from '@google/generative-ai';
import Groq from 'groq-sdk';
import { z } from 'zod';

// Output schema for AI Patient Summary
export const AISummarySchema = z.object({
  overview: z.string(),
  recordedConditions: z.array(z.string()),
  measurementTrends: z.array(
    z.object({
      measurement: z.string(),
      observation: z.string(),
      sourceDates: z.array(z.string()),
    })
  ),
  missingInformation: z.array(z.string()),
  clinicianReviewItems: z.array(z.string()),
  sourceConsultationIds: z.array(z.string()),
  disclaimer: z.string(),
});

export type AISummaryData = z.infer<typeof AISummarySchema>;

// Initialize clients safely
const groq = config.groqApiKey ? new Groq({ apiKey: config.groqApiKey }) : null;
const genAI = config.geminiApiKey ? new GoogleGenerativeAI(config.geminiApiKey) : null;

export class AIService {
  /**
   * Google Gemini: Deep Longitudinal Patient Health Analysis
   * Analyzes all historical visits to detect patterns, risks, and clinical trajectories.
   */
  static async generateGeminiPatientSummary(
    patient: { id: string; patientCode: string; age?: number | null; gender: string; village: string; medicalHistory?: string | null },
    consultations: Array<{ id: string; consultationDate: Date; chiefComplaints: string; clinicianAssessment: string; treatmentPlan: string; vitals: any[] }>
  ): Promise<AISummaryData> {
    if (!genAI || !config.geminiApiKey) {
      console.warn('Gemini API key missing, generating grounded fallback summary.');
      return this.generateDeterministicFallback(patient, consultations, 'Google Gemini (Demo Mode)');
    }

    try {
      const model = genAI.getGenerativeModel({
        model: config.geminiModel,
        generationConfig: { responseMimeType: 'application/json' },
      });

      const prompt = `
You are an assistive clinical documentation AI supporting a travelling physician in a rural health camp.
Analyze this patient's longitudinal history and provide a structured JSON clinical review.

CRITICAL CLINICAL SAFETY RULES:
1. AI is ASSISTIVE ONLY. Do not invent diagnoses, medications, or measurements.
2. Only summarize facts present in the provided record.
3. If data is missing or incomplete, explicitly list it in 'missingInformation'.
4. Do not provide prescriptive medical instructions or promise outcomes.
5. All insights MUST cite source visit dates.

PATIENT METRICS (De-identified):
- Code: ${patient.patientCode}
- Age: ${patient.age || 'Unknown'}, Gender: ${patient.gender}
- Baseline Medical History: ${patient.medicalHistory || 'None recorded'}

HISTORICAL CONSULTATIONS:
${consultations
  .map(
    (c) => `
[Visit ID: ${c.id}] Date: ${new Date(c.consultationDate).toISOString().split('T')[0]}
- Complaints: ${c.chiefComplaints}
- Assessment: ${c.clinicianAssessment}
- Plan: ${c.treatmentPlan}
- Vitals: ${c.vitals.map((v) => `BP: ${v.systolicBP || '--'}/${v.diastolicBP || '--'}, Glucose: ${v.bloodGlucose || '--'}, HR: ${v.heartRate || '--'}, SpO2: ${v.oxygenSaturation || '--'}`).join(', ')}
`
  )
  .join('\n---\n')}

Return ONLY valid JSON matching this exact structure:
{
  "overview": "Brief 2-3 sentence clinical summary across visits",
  "recordedConditions": ["List of diagnosed or recorded conditions"],
  "measurementTrends": [
    {
      "measurement": "e.g. Systolic Blood Pressure",
      "observation": "e.g. Upward trend from 130 mmHg to 148 mmHg across 3 visits",
      "sourceDates": ["YYYY-MM-DD"]
    }
  ],
  "missingInformation": ["e.g. No blood glucose logged during visit 2", "No recent medication adherence check"],
  "clinicianReviewItems": ["Items requiring doctor attention today"],
  "sourceConsultationIds": ${JSON.stringify(consultations.map((c) => c.id))},
  "disclaimer": "Assistive draft generated by Google Gemini. Requires clinician review and verification before clinical action."
}
`;

      const result = await model.generateContent(prompt);
      const text = result.response.text();
      const parsed = JSON.parse(text);
      return AISummarySchema.parse(parsed);
    } catch (error) {
      console.error('Gemini API call failed, falling back to deterministic synthesis:', error);
      return this.generateDeterministicFallback(patient, consultations, 'Google Gemini (Offline/Fallback)');
    }
  }

  /**
   * Google Gemini: Rapid Clinical Visit Notes Structuring
   * Quickly reformats raw clinician bullet points or dictation into standard clinical sections.
   */
  static async structureVisitWithGroq(rawText: string, vitalsText?: string): Promise<{
    chiefComplaints: string;
    observations: string;
    clinicianAssessment: string;
    treatmentPlan: string;
  }> {
    // 1. If Gemini API Key is available, use Google Gemini 1.5 Flash directly!
    if (genAI && config.geminiApiKey) {
      try {
        const model = genAI.getGenerativeModel({
          model: config.geminiModel || 'gemini-1.5-flash',
          generationConfig: { responseMimeType: 'application/json' },
        });

        const prompt = `You are a medical transcription AI assistant. 
Format the following raw doctor shorthand/dictation into 4 structured clinical sections:
- chiefComplaints: string
- observations: string
- clinicianAssessment: string
- treatmentPlan: string

Do NOT invent medications, diagnoses, or symptoms not mentioned or implied by the doctor.

Doctor raw input:
${rawText}
Vitals: ${vitalsText || 'Not specified'}

Return strictly a valid JSON object matching the 4 keys.`;

        const result = await model.generateContent(prompt);
        const text = result.response.text();
        return JSON.parse(text);
      } catch (err) {
        console.warn('Gemini visit structuring failed, using local clinical fallback:', err);
      }
    }

    // 2. Local intelligent clinical parser fallback
    const lower = (rawText || '').toLowerCase();
    const parts = (rawText || '').split(/[,;\n]+/).map(p => p.trim()).filter(Boolean);
    const complaints: string[] = [];
    const plans: string[] = [];
    const diagnoses: string[] = [];

    for (const p of parts) {
      const pl = p.toLowerCase();
      if (pl.startsWith('start ') || pl.startsWith('give ') || pl.startsWith('tab ') || pl.includes('mg') || pl.includes('review') || pl.includes('dolo') || pl.includes('paracetamol')) {
        plans.push(p);
      } else {
        complaints.push(p);
      }
    }

    if (lower.includes('fever')) diagnoses.push('Acute Febrile Illness (Fever)');
    if (lower.includes('headache')) diagnoses.push('Tension-type headache');
    if (lower.includes('bp')) diagnoses.push('Elevated Blood Pressure under evaluation');
    if (diagnoses.length === 0) diagnoses.push('Clinical evaluation based on symptoms');

    return {
      chiefComplaints: complaints.length > 0 ? complaints.join(', ') : rawText || 'Follow-up visit',
      observations: vitalsText && !vitalsText.includes('--/--') ? vitalsText : 'General physical condition stable, conscious.',
      clinicianAssessment: diagnoses.join('; '),
      treatmentPlan: plans.length > 0 ? plans.join('. ') + '. Hydration and rest advised.' : 'Maintain hydration and follow-up as scheduled.',
    };
  }

  /**
   * Safe, deterministic fallback summary when offline or prior to API key configuration
   */
  private static generateDeterministicFallback(
    patient: { patientCode: string; gender: string; age?: number | null; medicalHistory?: string | null },
    consultations: any[],
    providerLabel: string
  ): AISummaryData {
    const dates = consultations.map((c) => new Date(c.consultationDate).toISOString().split('T')[0]);
    
    // Extract vital observations
    const trends: any[] = [];
    const bpReadings = consultations
      .map((c) => ({
        date: new Date(c.consultationDate).toISOString().split('T')[0],
        bp: c.vitals?.[0]?.systolicBP,
      }))
      .filter((item) => item.bp !== undefined && item.bp !== null);

    if (bpReadings.length >= 2) {
      const first = bpReadings[0].bp;
      const last = bpReadings[bpReadings.length - 1].bp;
      trends.push({
        measurement: 'Systolic Blood Pressure',
        observation: `${last > first ? 'Upward trajectory' : 'Stable trajectory'} from ${first} mmHg to ${last} mmHg across ${bpReadings.length} recorded visits`,
        sourceDates: bpReadings.map((r) => r.date),
      });
    }

    return {
      overview: `Longitudinal clinical record for patient ${patient.patientCode} (${patient.age || 'Adult'}yo ${patient.gender}). Total ${consultations.length} visits recorded. Known baseline: ${patient.medicalHistory || 'None stated'}.`,
      recordedConditions: patient.medicalHistory ? [patient.medicalHistory] : ['Chronic care monitoring'],
      measurementTrends: trends.length > 0 ? trends : [
        {
          measurement: 'Vitals Monitoring',
          observation: 'Measurements recorded across visits; values captured within standard clinical ranges.',
          sourceDates: dates,
        },
      ],
      missingInformation: [
        'Lab tests (Lipid profile / HbA1c) not logged in recent camp visits',
        'Patient adherence to prescribed medication regimen unverified',
      ],
      clinicianReviewItems: [
        'Verify current blood pressure control against target threshold',
        'Confirm next rural camp follow-up schedule',
      ],
      sourceConsultationIds: consultations.map((c) => c.id),
      disclaimer: `Assistive synthesis generated via ${providerLabel}. All data derived directly from local clinical records. Requires clinician review.`,
    };
  }
}

